const dictionaries: Record<Locale, Record<string, string>> = { zh, en };

export function t(locale: Locale, key: string): string {
  return dictionaries[locale]?.[key] ?? dictionaries.zh[key] ?? key;
}

export function interpolate(template: string, vars: Record<string, string | number>): string {
  return Object.entries(vars).reduce((text, [key, value]) => text.replaceAll(`{${key}}`, String(value)), template);
}
